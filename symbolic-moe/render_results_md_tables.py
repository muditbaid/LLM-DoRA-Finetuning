#!/usr/bin/env python3
"""Convert simple markdown result tables into LaTeX table blocks."""
from __future__ import annotations

import argparse
from pathlib import Path


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--results-dir",
        type=Path,
        default=Path(__file__).resolve().parent / "results",
        help="Directory containing markdown result summaries.",
    )
    return parser.parse_args()


def escape_tex(text: str) -> str:
    replacements = {
        "\\": "\\textbackslash{}",
        "&": "\\&",
        "%": "\\%",
        "_": "\\_",
        "#": "\\#",
    }
    out = text
    for src, dst in replacements.items():
        out = out.replace(src, dst)
    return out


def strip_backticks(text: str) -> str:
    return text.replace("`", "")


def infer_alignment(headers: list[str]) -> str:
    cols = ["l"]
    for _ in headers[1:]:
        cols.append("c")
    return "".join(cols)


def clean_caption(title: str, section: str) -> str:
    if section.lower() == "overall":
        return f"{title} overall metrics."
    if section.lower() == "overall routing":
        return f"{title} overall routing metrics."
    return f"{title} {section.lower()}."


def parse_md_tables(path: Path) -> tuple[str, list[tuple[str, list[str], list[list[str]]]]]:
    lines = path.read_text(encoding="utf-8").splitlines()
    title = path.stem.replace("_", " ").title()
    sections: list[tuple[str, list[str], list[list[str]]]] = []
    current_heading: str | None = None
    i = 0
    while i < len(lines):
        line = lines[i].rstrip()
        if line.startswith("# "):
            title = line[2:].strip()
            i += 1
            continue
        if line.startswith("## "):
            current_heading = line[3:].strip()
            i += 1
            continue
        if line.strip().startswith("|"):
            table_lines: list[str] = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                table_lines.append(lines[i].strip())
                i += 1
            if len(table_lines) >= 2:
                header = [strip_backticks(cell.strip()) for cell in table_lines[0].strip("|").split("|")]
                rows: list[list[str]] = []
                for raw in table_lines[2:]:
                    row = [strip_backticks(cell.strip()) for cell in raw.strip("|").split("|")]
                    rows.append(row)
                sections.append((current_heading or "Table", header, rows))
            continue
        i += 1
    return title, sections


def render_table(title: str, section: str, header: list[str], rows: list[list[str]]) -> str:
    align = infer_alignment(header)
    lines = [
        "\\begin{table}[t]",
        "\\centering",
        f"\\caption{{{escape_tex(clean_caption(title, section))}}}",
        f"\\begin{{tabular}}{{{align}}}",
        "\\toprule",
        " & ".join(escape_tex(cell) for cell in header) + " \\\\",
        "\\midrule",
    ]
    for row in rows:
        lines.append(" & ".join(escape_tex(cell) for cell in row) + " \\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}"])
    return "\n".join(lines)


def render_tex(path: Path) -> str:
    title, sections = parse_md_tables(path)
    lines = [
        "% Auto-generated by symbolic-moe/render_results_md_tables.py",
        "% Requires: \\usepackage{booktabs}",
    ]
    if not sections:
        lines.append(f"% No markdown tables found in {path.name}")
        return "\n".join(lines) + "\n"

    for idx, (section, header, rows) in enumerate(sections):
        if idx:
            lines.append("")
        lines.append(render_table(title, section, header, rows))
    return "\n".join(lines) + "\n"


def main() -> None:
    args = parse_args()
    md_paths = sorted(args.results_dir.glob("*.md"))
    for md_path in md_paths:
        tex_path = md_path.with_suffix(".tex")
        tex_path.write_text(render_tex(md_path), encoding="utf-8")
        print(f"Wrote {tex_path}")


if __name__ == "__main__":
    main()
